#ifndef CATOS_LIBCFG_H
#define CATOS_LIBCFG_H

/* ============================================================
 * CatOS 运行库配置（lib/）
 *
 * 运行库位于内核核心层之下，不依赖任何宿主库（FR-LIB-003）：
 * 同一份实现可在 Windows 与各嵌入式目标上编译运行。
 * 本头文件是运行库的配置入口；修改后需重新编译。
 * ============================================================ */

/* 单条格式化消息的缓冲上限（字节，含结尾 '\0'）。
 * 超出部分被截断，见 catos_stdio.h。 */
#define CATOS_CFG_LOG_BUF        128

/* 格式串里宽度/精度的上限（如 "%999999d"）。
 * 超过时按本值处理——防止天文数字宽度导致长时间的填充循环。 */
#define CATOS_CFG_MAX_WIDTH      256

/* 换行序列配置（FR-LIB-009）：
 *   - 系统自身消息（panic、将来的内核日志）默认使用 CATOS_CFG_NL；
 *   - 应用输出**不做任何翻译**——运行库写出什么字节就是什么字节，
 *     应用要 CRLF 就在自己的格式串里写 "\r\n"。
 *   - 若某个应用希望沿用"本平台的惯用换行"，可在自己的格式串里使用 CATOS_NL
 *     （本配置的别名），从而由本项统一控制；不使用则应用自行决定。
 *
 * 默认 "\n"：与 Linux、串口、管道/文件输出逐字节一致（跨平台一致）。
 * 改为 "\r\n" 会更适合老式 Windows 控制台（conhost）的人工观看，
 * 但会让重定向输出比 Linux 多一个字节。 */
#ifndef CATOS_CFG_NL
#define CATOS_CFG_NL             "\n"
#endif

#define CATOS_NL                 CATOS_CFG_NL

#endif /* CATOS_LIBCFG_H */
